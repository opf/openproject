import { Controller } from '@hotwired/stimulus';

// Shows the question field and its buttons when the user chooses to chat about a skill's answer.
export default class extends Controller {
  static targets = ['control', 'openButton'];

  declare readonly controlTargets:HTMLElement[];
  declare readonly openButtonTarget:HTMLElement;

  open():void {
    this.controlTargets.forEach((control) => control.classList.remove('d-none'));
    this.openButtonTarget.classList.add('d-none');
    this.element.querySelector('textarea')?.focus();
  }
}
