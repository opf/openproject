require "spec_helper"

RSpec.describe AI::TextTransformRun do
  subject(:run) { build(:ai_text_transform_run) }

  it { is_expected.to validate_presence_of(:system_prompt) }
  it { is_expected.to validate_presence_of(:input) }
  it { is_expected.to validate_length_of(:input).is_at_most(described_class::MAX_INPUT_LENGTH) }

  describe "status" do
    it "defaults to queued" do
      expect(described_class.new.status).to eq("queued")
    end

    it "allows only the defined values" do
      expect(described_class.statuses.keys)
        .to contain_exactly("queued", "running", "succeeded", "failed", "cancelled")
    end

    it "adds a validation error for unknown values" do
      run.status = "exploded"

      expect(run).not_to be_valid
      expect(run.errors[:status]).to be_present
    end
  end

  describe "uuid" do
    it "is generated on build" do
      expect(run.uuid).to be_present
      expect(build(:ai_text_transform_run).uuid).not_to eq(run.uuid)
    end

    it "is unique" do
      existing = create(:ai_text_transform_run)

      expect { create(:ai_text_transform_run, uuid: existing.uuid) }.to raise_error(ActiveRecord::RecordNotUnique)
    end

    it "is generated by the database when the Ruby default is skipped" do
      template = create(:ai_text_transform_run)
      attributes = template.attributes.slice("user_id", "ai_text_action_id", "system_prompt", "input")

      described_class.insert!(attributes)

      expect(described_class.where.not(id: template.id).pick(:uuid)).to be_present
    end

    it "does not match malformed values" do
      create(:ai_text_transform_run)

      expect(described_class.find_by(uuid: "not-a-uuid")).to be_nil
    end
  end

  describe "#append_event" do
    subject(:run) { create(:ai_text_transform_run) }

    it "assigns consecutive sequence numbers" do
      events = Array.new(3) { run.append_event("text_delta", { "delta" => "x" }) }

      expect(events.map(&:seq)).to eq([1, 2, 3])
      expect(events).to all(be_persisted)
      expect(events.first.payload).to eq({ "delta" => "x" })
    end

    it "rejects a duplicate sequence number through the unique index" do
      run.append_event("text_delta")

      duplicate = { run_id: run.id, seq: 1, kind: "status", payload: {}, created_at: Time.current }

      expect { AI::TextTransformRunEvent.insert!(duplicate) }.to raise_error(ActiveRecord::RecordNotUnique)
    end
  end

  describe "#append_event_while_active" do
    subject(:run) { create(:ai_text_transform_run, :running) }

    it "appends the event to an active run" do
      run.append_event_while_active("text_delta", delta: "x")

      expect(run.events.map { [it.kind, it.payload] }).to eq([["text_delta", { "delta" => "x" }]])
    end

    it "appends nothing once the run has ended" do
      run.fail!(:interrupted)

      expect(run.append_event_while_active("text_delta", delta: "x")).to be_nil
      expect(run.events.map(&:kind)).to eq(%w[error])
    end
  end

  describe "#events_after" do
    subject(:run) { create(:ai_text_transform_run) }

    it "returns the events after the given sequence number in order" do
      run.append_event("text_delta")
      second = run.append_event("text_delta")
      third = run.append_event("completed")

      expect(run.events_after(1)).to eq([second, third])
      expect(run.events_after(3)).to be_empty
    end
  end

  describe "#start!" do
    subject(:run) { create(:ai_text_transform_run) }

    it "sets the status to running and records it as the first event" do
      expect(run.start!).to be(true)

      expect(run.reload).to be_running
      expect(run.finished_at).to be_nil
      expect(run.events.map { [it.kind, it.payload] }).to eq([["status", { "status" => "running" }]])
    end

    it "leaves a run that is no longer queued as it is" do
      described_class.where(id: run.id).update_all(status: "failed")

      expect(run.start!).to be(false)
      expect(run.reload).to be_failed
      expect(run.events).to be_empty
    end
  end

  describe "#finish!" do
    subject(:run) { create(:ai_text_transform_run, :running) }

    it "sets a terminal status and the finished_at timestamp" do
      run.finish!("succeeded")

      expect(run.reload).to be_succeeded
      expect(run.finished_at).to be_within(5.seconds).of(Time.current)
      expect(run.error_message).to be_nil
    end

    it "stores the error message" do
      run.finish!("failed", error_message: "boom")

      expect(run.reload).to be_failed
      expect(run.error_message).to eq("boom")
      expect(run.finished_at).to be_present
    end

    it "rejects non-terminal statuses" do
      expect { run.finish!("running") }.to raise_error(ArgumentError, /not a terminal status/)
      expect(run.reload).to be_running
    end

    it "leaves a run that another writer finished first as it is" do
      described_class.where(id: run.id).update_all(status: "failed", error_message: "first")

      expect(run.finish!("succeeded")).to be(false)
      expect(run.reload).to have_attributes(status: "failed", error_message: "first")
    end
  end

  describe "#succeed!" do
    subject(:run) { create(:ai_text_transform_run, :running) }

    it "succeeds the run and records the text as a completed event" do
      expect(run.succeed!("done")).to be(true)

      expect(run.reload).to have_attributes(status: "succeeded", finished_at: be_present)
      expect(run.events.map { [it.kind, it.payload] }).to eq([["completed", { "text" => "done" }]])
    end

    it "leaves a run that already failed and its events as they are" do
      run.fail!(:interrupted)

      expect(run.succeed!("done")).to be(false)
      expect(run.reload).to be_failed
      expect(run.events.map(&:kind)).to eq(%w[error])
    end
  end

  describe "#fail!" do
    subject(:run) { create(:ai_text_transform_run, :running) }

    it "fails the run with the translated message and records it as an error event" do
      expect(run.fail!(:interrupted)).to be(true)

      message = "Generating the text was interrupted before it finished."
      expect(run.reload).to have_attributes(status: "failed", error_message: message, finished_at: be_present)
      expect(run.events.map { [it.kind, it.payload] }).to eq([["error", { "message" => message, "reason" => "interrupted" }]])
    end

    it "leaves a finished run and its events as they are" do
      run.finish!("succeeded")

      expect(run.fail!(:interrupted)).to be(false)
      expect(run.reload).to be_succeeded
      expect(run.events).to be_empty
    end
  end

  describe "#stalled?" do
    let(:quiet) { described_class::STALLED_AFTER + 1.minute }

    it "is true for a running run without an event for longer than the budget allows" do
      running = create(:ai_text_transform_run, :running, updated_at: quiet.ago)
      create(:ai_text_transform_run_event, run: running, created_at: quiet.ago)

      expect(running).to be_stalled
    end

    it "is false for a run still waiting in the queue, as its job has not used any of the budget yet" do
      expect(create(:ai_text_transform_run, updated_at: quiet.ago)).not_to be_stalled
    end

    it "is false while events keep coming" do
      running = create(:ai_text_transform_run, :running, updated_at: quiet.ago)
      create(:ai_text_transform_run_event, run: running, created_at: 1.minute.ago)

      expect(running).not_to be_stalled
      expect(create(:ai_text_transform_run, :running, updated_at: 1.minute.ago)).not_to be_stalled
    end

    it "is false for a finished run" do
      expect(create(:ai_text_transform_run, :succeeded, updated_at: quiet.ago)).not_to be_stalled
    end
  end

  describe "#fail_if_stalled!" do
    let(:quiet) { described_class::STALLED_AFTER + 1.minute }

    it "fails a stalled run as interrupted" do
      run = create(:ai_text_transform_run, :running, updated_at: quiet.ago)

      expect(run.fail_if_stalled!).to be(true)
      expect(run.reload).to have_attributes(status: "failed")
      expect(run.events.last.payload).to include("reason" => "interrupted")
    end

    it "ends a stalled run as cancelled when its cancellation was requested, even though that touches the run" do
      run = create(:ai_text_transform_run, :running, created_at: quiet.ago, updated_at: quiet.ago)
      run.request_cancel!

      expect(run.reload.fail_if_stalled!).to be(true)
      expect(run.reload).to be_cancelled
      expect(run.events).to be_empty
    end

    it "leaves a run alone that is still active" do
      run = create(:ai_text_transform_run, :running, updated_at: 1.minute.ago)

      expect(run.fail_if_stalled!).to be(false)
      expect(run.reload).to be_running
    end

    it "leaves a run alone that its job moved on after the run was loaded" do
      run = create(:ai_text_transform_run, :running, updated_at: quiet.ago)
      described_class.where(id: run.id).update_all(updated_at: Time.current)

      expect(run.fail_if_stalled!).to be(false)
      expect(run.reload).to be_running
      expect(run.events).to be_empty
    end
  end

  describe "#request_cancel!" do
    it "flags a running run for cancellation" do
      run = create(:ai_text_transform_run, :running, updated_at: 1.hour.ago)

      run.request_cancel!

      expect(run.reload).to have_attributes(cancel_requested: true, updated_at: be_within(1.minute).of(Time.current))
    end

    it "leaves a terminal run untouched" do
      run = create(:ai_text_transform_run, :succeeded)

      run.request_cancel!

      expect(run.reload.cancel_requested).to be(false)
    end

    it "does not depend on the run being valid" do
      run = create(:ai_text_transform_run, :running)
      run.update_column(:input, "x" * (AI::TextTransformRun::MAX_INPUT_LENGTH + 1))

      expect { run.reload.request_cancel! }.not_to raise_error
      expect(run.reload.cancel_requested).to be(true)
    end
  end

  describe "finished_at" do
    subject(:run) { create(:ai_text_transform_run, :running) }

    it "is stamped when a status bang method reaches a terminal status" do
      run.cancelled!

      expect(run.reload.finished_at).to be_within(5.seconds).of(Time.current)
    end

    it "keeps an explicitly assigned value" do
      run.update!(status: "succeeded", finished_at: 10.minutes.ago)

      expect(run.reload.finished_at).to be_within(5.seconds).of(10.minutes.ago)
    end

    it "stays empty while the run is not terminal" do
      run.update!(status: "queued")

      expect(run.reload.finished_at).to be_nil
    end
  end

  describe "#terminal?" do
    it "is false for queued and running" do
      expect(build(:ai_text_transform_run)).not_to be_terminal
      expect(build(:ai_text_transform_run, :running)).not_to be_terminal
    end

    it "is true for succeeded, failed and cancelled" do
      expect(build(:ai_text_transform_run, :succeeded)).to be_terminal
      expect(build(:ai_text_transform_run, :failed)).to be_terminal
      expect(build(:ai_text_transform_run, :cancelled)).to be_terminal
    end
  end

  describe ".expired" do
    let(:retention) { 5.minutes }

    it "includes runs finished before the retention period" do
      expired = create(:ai_text_transform_run, :succeeded, finished_at: 10.minutes.ago)
      create(:ai_text_transform_run, :succeeded, finished_at: Time.current)

      expect(described_class.expired(retention)).to contain_exactly(expired)
    end

    it "includes unfinished runs created before the retention period" do
      stale = create(:ai_text_transform_run, :running, created_at: 10.minutes.ago)
      create(:ai_text_transform_run, :running, created_at: Time.current)

      expect(described_class.expired(retention)).to contain_exactly(stale)
    end
  end

  describe "#destroy" do
    it "deletes the events of the run" do
      run = create(:ai_text_transform_run)
      run.append_event("text_delta")
      run.append_event("completed")

      expect { run.destroy! }.to change(AI::TextTransformRunEvent, :count).from(2).to(0)
    end
  end
end
