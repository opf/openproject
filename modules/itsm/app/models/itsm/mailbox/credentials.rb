module ITSM
  module Mailbox
    # Keeps the password out of logs, string interpolation and the console:
    # Data's to_s and pp print every member and don't go through an overridden inspect.
    Credentials = Data.define(:username, :password) do
      def inspect = "#<#{self.class.name} username=#{username.inspect}>"
      def to_s = inspect
      def pretty_print(printer) = printer.text(inspect)
    end
  end
end
