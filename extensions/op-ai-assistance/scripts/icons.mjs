import { deflateSync } from 'node:zlib';

const BLUE = [26, 103, 163];
const WHITE = [255, 255, 255];

const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k += 1) {
    c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  }
  return c >>> 0;
});

function crc32(buffer) {
  let crc = 0xffffffff;
  for (const byte of buffer) {
    crc = crcTable[(crc ^ byte) & 0xff] ^ (crc >>> 8);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([length, body, crc]);
}

// A four-pointed star (|x|^p + |y|^p <= 1 with p < 1) on a rounded blue square.
function pixel(x, y, size) {
  const u = ((x + 0.5) / size) * 2 - 1;
  const v = ((y + 0.5) / size) * 2 - 1;
  const corner = 0.35;
  const dx = Math.max(Math.abs(u) - (1 - corner), 0);
  const dy = Math.max(Math.abs(v) - (1 - corner), 0);
  if (dx * dx + dy * dy > corner * corner) {
    return [0, 0, 0, 0];
  }
  const star = Math.abs(u / 0.72) ** 0.55 + Math.abs(v / 0.72) ** 0.55;
  return star <= 1 ? [...WHITE, 255] : [...BLUE, 255];
}

export function sparklePng(size) {
  const raw = Buffer.alloc((size * 4 + 1) * size);
  for (let y = 0; y < size; y += 1) {
    const row = y * (size * 4 + 1);
    raw[row] = 0;
    for (let x = 0; x < size; x += 1) {
      pixel(x, y, size).forEach((value, channel) => {
        raw[row + 1 + x * 4 + channel] = value;
      });
    }
  }

  const header = Buffer.alloc(13);
  header.writeUInt32BE(size, 0);
  header.writeUInt32BE(size, 4);
  header.set([8, 6, 0, 0, 0], 8);

  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', header),
    chunk('IDAT', deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}
