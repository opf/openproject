module AI
  module Assistance
    # The locale that a run or an answer is written in: the user's language when
    # OpenProject offers it, otherwise the default.
    module Locale
      def self.for(user)
        locale = user.language.presence&.to_sym
        I18n.available_locales.include?(locale) ? locale : I18n.default_locale
      end
    end
  end
end
