module WikiPages
  class SidemenuTreeNodeComponent < ApplicationComponent
    def initialize(component:, node:)
      super()

      @component = component
      @node = node
    end

    private

    def page = @node[:page]
    def children = @node[:children]
    def current? = @node[:current]
    def expanded? = @node[:expanded]
    def matches_query? = @node[:matches_query]

    def href
      helpers.project_wiki_path(page.project, page)
    end
  end
end
